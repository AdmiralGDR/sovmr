///
/// The model was confirmed by prediction before any of it was written
/// down: six magnitudes were encoded by this rule, handed to a decoder,
/// and all six came back exactly as predicted.
///
/// Returns `None` below [`ESCAPE_MAGNITUDE`], where there is nothing
/// to escape, and above what the format can carry.
pub fn escape_sequence(magnitude: i32) -> Option<(u32, u8)> {
    if magnitude < ESCAPE_MAGNITUDE {
        return None;
    }
    let magnitude = magnitude as u32;
    let mut n = 0u32;
    // Grow the payload until the magnitude fits inside its range.
    while n + 4 < u32::BITS && magnitude >= (1 << (n + 4)) * 2 {
        n += 1;
    }
    let width = n + 4;
    let payload = magnitude.checked_sub(1 << width)?;
    // n ones, a zero, then the payload.
    let length = n + 1 + width;
    if length > u32::BITS {
        return None;
    }
    let prefix = ((1u32 << n) - 1) << 1;
    Some((prefix << width | payload, length as u8))
}

