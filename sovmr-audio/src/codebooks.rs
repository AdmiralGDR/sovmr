/// Index of a four-coefficient tuple in a book of the given range.
///
/// Returns  when any value is outside the book, which is the
/// question an encoder actually asks: not "what is the index" but "can
/// this book carry this tuple at all".
pub fn quad_index(tuple: [i32; 4], range: i32) -> Option<usize> {
    let side = 2 * range + 1;
    let mut index = 0usize;
    for value in tuple {
        if value < -range || value > range {
            return None;
        }
        index = index * side as usize + (value + range) as usize;
    }
    Some(index)
}

/// The codeword a book gives a tuple, or `None` if it cannot carry
/// it.
pub fn quad_codeword(book: &[Codeword], tuple: [i32; 4], range: i32) -> Option<Codeword> {
    quad_index(tuple, range).map(|i| book[i])
}

