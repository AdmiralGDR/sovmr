/// Index of a two-coefficient pair in a book of the given range.
///
/// `None` when either value is outside the book — the question an
/// encoder asks before choosing one.
pub fn pair_index(pair: [i32; 2], range: i32) -> Option<usize> {
    let side = 2 * range + 1;
    let mut index = 0usize;
    for value in pair {
        if value < -range || value > range {
            return None;
        }
        index = index * side as usize + (value + range) as usize;
    }
    Some(index)
}

/// The codeword a pair book gives a pair, or `None` if it cannot
/// carry it.
pub fn pair_codeword(book: &[Pair], pair: [i32; 2], range: i32) -> Option<Pair> {
    pair_index(pair, range).map(|i| book[i])
}

