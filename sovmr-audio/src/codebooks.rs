//! The spectral Huffman codebooks, measured out of a decoder.
//!
//! # What these are
//!
//! AAC codes its quantised coefficients in groups, and a codebook says
//! which bit string stands for which group. There are eleven of them and
//! an encoder must reproduce them exactly: a codeword off by one bit is
//! not a small error, it desynchronises the rest of the frame.
//!
//! This module carries the four that take four coefficients at a time.
//! Books 1 and 2 cover values from minus one to one; books 3 and 4 cover
//! minus two to two, and pay for the wider range in longer codewords.
//! An encoder picks whichever fits the band and costs least.
//!
//! # Where the numbers came from
//!
//! Measured, not remembered and not copied.
//! walks the code tree: it offers a decoder a bit pattern, and when the
//! frame decodes with nothing left over the pattern was exactly one
//! codeword. What it stood for is then read back out of the decoded
//! audio with this project's own transform.
//!
//! A prefix code makes the walk cheap. Nothing with a complete codeword
//! as a proper prefix can be one itself, so whole subtrees are skipped —
//! books 3 and 4 have six hundred and twenty-five codewords each and
//! took twelve hundred probes to find them all.
//!
//! # Why they can be trusted
//!
//! Each book came back **complete and exact**: eighty-one codewords for
//! a book over three values in four positions, six hundred and
//! twenty-five for a book over five. Every tuple appeared once, no
//! codeword was a prefix of another, and every coefficient read back
//! within a hundred-thousandth of an integer.
//!
//! None of that is arranged by the measurement. Each codeword was probed
//! on its own; that they form a complete prefix code over exactly the
//! expected tuples is a statement about all of them together.
//!
//! Signs are part of the bit string here. Two of these books code
//! magnitudes and append a sign bit per non-zero value, but an encoder
//! that emits what this table says never has to know which two.

/// A codeword: the bits, most significant first, and how many.
///
/// Length is not implied by the value — a codeword may begin with zeros,
/// and dropping them would emit a different, shorter codeword that means
/// something else entirely.
pub type Codeword = (u32, u8);

